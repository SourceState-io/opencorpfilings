"""Generate API.md from the public objects' signatures and docstrings.

Example:
    python scripts/api_reference.py > API.md

The reference is derived from `opencorpfilings.__all__`, so it cannot
describe a method the code lacks. tests/test_api_reference.py checks that the
committed API.md matches this output.
"""

from __future__ import annotations

import dataclasses
import inspect

import opencorpfilings as package

SKIP_BASES = {"Exception", "BaseException", "ABC", "object"}


def _summary(obj) -> str:
    doc = inspect.getdoc(obj) or ""
    if inspect.isclass(obj) and dataclasses.is_dataclass(obj) and doc.startswith(f"{obj.__name__}("):
        return ""  # the dataclass default docstring is its constructor signature
    return doc.split("\n\n", 1)[0].replace("\n", " ").strip()


def _signature(obj) -> str:
    try:
        return str(inspect.signature(obj))
    except (TypeError, ValueError):
        return "(...)"


def _members(cls) -> list[tuple[str, object]]:
    members = []
    for name, value in vars(cls).items():
        if name.startswith("_") or name in {"name", "market", "regulator", "capabilities"}:
            continue
        if isinstance(value, (property, staticmethod, classmethod)) or inspect.isfunction(value):
            members.append((name, value))
    return sorted(members)


def render() -> str:
    lines = ["# API reference", "",
             "Generated by `scripts/api_reference.py` from the package's public names; do not edit by hand.", ""]
    names = sorted(package.__all__, key=str.casefold)
    for name in names:
        obj = getattr(package, name)
        if inspect.isclass(obj):
            kind = "exception" if issubclass(obj, BaseException) else "class"
            lines += [f"## `{name}` ({kind})", ""]
            if summary := _summary(obj):
                lines += [summary, ""]
            if dataclasses.is_dataclass(obj):
                public = [field.name for field in dataclasses.fields(obj) if not field.name.startswith("_")]
                lines += ["Fields: " + ", ".join(f"`{field}`" for field in public), ""]
            if kind == "class":
                for member, value in _members(obj):
                    target = value.fget if isinstance(value, property) else getattr(value, "__func__", value)
                    label = f"`{member}`" if isinstance(value, property) else f"`{member}{_signature(target)}`"
                    summary = _summary(target)
                    lines.append(f"- {label}" + (f": {summary}" if summary else ""))
                lines.append("")
            else:
                parents = [base.__name__ for base in obj.__bases__ if base.__name__ not in SKIP_BASES]
                if parents:
                    lines += [f"Subclass of `{', '.join(parents)}`.", ""]
        elif callable(obj):
            lines += [f"## `{name}{_signature(obj)}`", ""]
            if summary := _summary(obj):
                lines += [summary, ""]
        else:
            lines += [f"## `{name}`", "", f"Constant: `{obj!r}`" if not isinstance(obj, frozenset)
                      else f"Constant: {', '.join(sorted(obj))}", ""]
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    print(render(), end="")
